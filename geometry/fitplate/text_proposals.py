"""Standalone program-side verification of a *limited* Chinese width-cap proposal.

**Not wired into production.** `intake.py`, the bridge, the client and the schema are untouched.
This module is the independent verifier designed in `reviews/038-limited-proposals-design.md`,
steps 1-2: the model may hand in only a *quote* plus an *assertion*; the program re-reads the real
request text and re-derives the number and the unit itself.

The quote must be **one complete single condition**, not a bag of keywords. After an optional
non-semantic prefix (whitespace / emoji) and a trailing sentence punctuation, it must read exactly
``<width-word><bound-word><number><unit>``:

* width words: ``板宽`` / ``板子宽度`` / ``板子横向`` / ``整个板子横向`` — a bare ``宽度``
  (subject ambiguous), a bare ``横向`` or ``传感器横向`` does **not** prove ``plate.width``;
* bound words: ``最多`` / ``不超过`` / ``至多`` / ``不大于`` / ``最大`` / ``≤`` / ``<=``;
* numbers: ASCII decimals (no exponent, no leading dot, no sign) or a strict Chinese integer
  1..999 (``九十九`` = 99, ``一百零九`` = 109, ``一百二十三`` = 123) with an optional decimal
  ``二十五点四`` = 25.4 / ``零点五`` = 0.5; ambiguous forms (``二三``, ``九十十``) are refused;
* units: mm/毫米, cm/厘米, m/米, in/英寸, um/微米.

The quote must be the **whole clause**: anything semantic outside it in the same clause (a
subject-changing word like ``传感器``, a negation, or an extra condition) refuses the proposal —
only whitespace, punctuation and emoji are tolerated. Any extra dimension — even the same number
with a different unit — also refuses. Number tokens are length-bounded and converted under the
contract's fixed 9-decimal quantum; a value below it is refused, never truncated toward zero.
The model's ``value``/``unit`` are assertions; ``source`` is generated by the program.
"""

from __future__ import annotations

import math
import re
import unicodedata
from typing import Any, Mapping

MAX_TEXT_CHARS = 8192
# A dimension token is short; a longer one is refused before any conversion (no Python
# OverflowError/ValueError may leak).
MAX_NUMBER_TOKEN_CHARS = 64

UNIT_FACTORS_MM = {"mm": 1.0, "cm": 10.0, "m": 1000.0, "um": 0.001, "in": 25.4}
UNIT_WORDS = {"mm": "mm", "毫米": "mm", "cm": "cm", "厘米": "cm", "m": "m", "米": "m",
              "um": "um", "微米": "um", "in": "in", "英寸": "in"}
_UNIT_ALT = "|".join(re.escape(w) for w in sorted(UNIT_WORDS, key=len, reverse=True))

# Explicit width phrases only: a bare 宽度 leaves the subject ambiguous, so it is refused.
# Longest first so 整个板子横向 wins over 板子横向 over 板子宽度 over 板宽.
_WIDTH_ALT = "|".join(re.escape(w) for w in (
    "整块底板横向", "整块板子横向", "整个板子横向", "底板横向", "底板宽度",
    "底板宽", "板子横向", "板子宽度", "板宽",
))
_BOUND_ALT = "|".join(re.escape(w) for w in ("不超过", "不大于", "至多", "最多", "最大", "<=", "≤"))

_CN_DIGITS = "零一二两三四五六七八九"
_CN_DIGIT_VALUE = {"零": 0, "一": 1, "二": 2, "两": 2, "三": 3, "四": 4,
                   "五": 5, "六": 6, "七": 7, "八": 8, "九": 9}
# Strict Chinese integer shape (1..999); 二三 / 九十十 do not match.
_CN_INT_SHAPE = (
    r"(?:[一二两三四五六七八九]百(?:零[一二两三四五六七八九]|[一二两三四五六七八九]?十[一二两三四五六七八九]?)?"
    r"|[一二两三四五六七八九]?十[一二两三四五六七八九]?|[一二两三四五六七八九])"
)
_CN_DEC_SHAPE = rf"(?:{_CN_INT_SHAPE}|零)点[零一二两三四五六七八九]+"
_NUM_SHAPE = rf"(?:\d+(?:\.\d+)?|{_CN_DEC_SHAPE}|{_CN_INT_SHAPE})"

_CLAUSE_RE = re.compile(rf"^({_WIDTH_ALT})\s*({_BOUND_ALT})\s*({_NUM_SHAPE})\s*({_UNIT_ALT})$")
# A broad "some number with a unit" scan for the surrounding clause.
_DIMENSION_SCAN = re.compile(rf"{_NUM_SHAPE}\s*(?:{_UNIT_ALT})")
_CLAUSE_PUNCT = "。；;，、\n\r！？!?：:"
_NEGATIONS = ("不是", "并非", "不要", "不再", "不必", "不用", "无须", "无需", "没有", "别", "勿", "不", "非")

_TOP_KEYS = {"field_path", "kind", "quote", "value", "unit"}
_QUOTE_KEYS = {"start", "end", "literal"}
_FORBIDDEN_KEYS = {"source", "hash", "confirmed", "draft_hash", "receipt", "session_scope"}


class ProposalError(ValueError):
    """A refused proposal. `code` is stable and machine-readable."""

    def __init__(self, code: str, message: str):
        super().__init__(message)
        self.code = code


def _fail(code: str, message: str) -> None:
    raise ProposalError(code, message)


# ---------------------------------------------------------------------------
# strict number parsing
# ---------------------------------------------------------------------------

def _cn_tens(token: str) -> int | None:
    if "十" in token:
        tens_text, _, units_text = token.partition("十")
        if tens_text and (len(tens_text) != 1 or tens_text not in _CN_DIGIT_VALUE):
            return None
        tens = _CN_DIGIT_VALUE[tens_text] if tens_text else 1
        if units_text == "":
            return tens * 10
        if len(units_text) == 1 and units_text in _CN_DIGIT_VALUE:
            return tens * 10 + _CN_DIGIT_VALUE[units_text]
        return None
    if len(token) == 1 and token in _CN_DIGIT_VALUE:
        return _CN_DIGIT_VALUE[token]
    return None


def _cn_integer(token: str) -> int | None:
    """Strict Chinese integer 1..999. Returns None when the shape is ambiguous."""
    if "百" in token:
        hundreds_text, _, rest = token.partition("百")
        if len(hundreds_text) != 1 or hundreds_text not in _CN_DIGIT_VALUE:
            return None
        total = _CN_DIGIT_VALUE[hundreds_text] * 100
        rest = rest.lstrip("零")
        if rest == "":
            return total
        tens = _cn_tens(rest)
        return None if tens is None else total + tens
    return _cn_tens(token)


def _parse_number(token: str) -> float:
    """Re-derive one positive finite number from a token that already matched the strict shape.

    The token length is bounded first, so a pathological "10**400"-style token or a many-thousand
    digit Chinese decimal is refused with a stable code instead of leaking a Python
    OverflowError/ValueError out of ``float``/``int``.
    """
    if len(token) > MAX_NUMBER_TOKEN_CHARS:
        _fail("PROPOSAL_NUMBER_TOO_LONG", f"the number token exceeds {MAX_NUMBER_TOKEN_CHARS} characters")
    try:
        if re.fullmatch(r"\d+(?:\.\d+)?", token):
            value = float(token)
        elif "点" in token:
            whole_text, _, fraction_text = token.partition("点")
            whole = 0 if whole_text == "零" else _cn_integer(whole_text)
            if whole is None or not fraction_text or any(c not in _CN_DIGIT_VALUE for c in fraction_text):
                _fail("PROPOSAL_NUMBER_AMBIGUOUS", f"cannot read the Chinese decimal {token!r}")
            value = whole + int("".join(str(_CN_DIGIT_VALUE[c]) for c in fraction_text)) / (10 ** len(fraction_text))
        else:
            integer = _cn_integer(token)
            if integer is None:
                _fail("PROPOSAL_NUMBER_AMBIGUOUS", f"cannot read the Chinese number {token!r}")
            value = float(integer)
    except ProposalError:
        raise
    except (OverflowError, ValueError):
        _fail("PROPOSAL_NUMBER_NOT_REPRESENTABLE", f"the number token {token!r} is not representable")
    if not math.isfinite(value) or value <= 0:
        _fail("PROPOSAL_VALUE_NOT_POSITIVE", f"the re-derived dimension {value!r} is not a positive finite number")
    return value


# ---------------------------------------------------------------------------
# closed object + decorations + clause context
# ---------------------------------------------------------------------------

def _check_closed(record: Mapping[str, Any], allowed: set[str], where: str) -> None:
    for key in record:
        if key in _FORBIDDEN_KEYS:
            _fail("PROPOSAL_FIELD_FORBIDDEN", f"{where}: the model may not supply {key!r}")
        if key not in allowed:
            _fail("PROPOSAL_FIELD_UNKNOWN", f"{where}: unknown key {key!r}")


def _strip_decorations(literal: str) -> str:
    """Drop a non-semantic prefix (whitespace / emoji-symbols) and trailing punctuation."""
    text = literal.strip()
    while text and unicodedata.category(text[0]) in ("So", "Sk", "Cf"):
        text = text[1:].lstrip()
    return text.rstrip(" \t。．.!！?？;；")


def _is_nonsemantic(char: str) -> bool:
    """Whitespace, punctuation or an emoji/symbol — never a subject-changing word."""
    if char.isspace() or char in _CLAUSE_PUNCT:
        return True
    return unicodedata.category(char) in ("So", "Sk", "Cf")


def _clause_context(text: str, start: int, end: int) -> str:
    """The same-clause characters outside the quote (to the nearest punctuation)."""
    before = text[:start]
    for index in range(len(before) - 1, -1, -1):
        if before[index] in _CLAUSE_PUNCT:
            before = before[index + 1:]
            break
    after = text[end:]
    for index, char in enumerate(after):
        if char in _CLAUSE_PUNCT:
            after = after[:index]
            break
    return before + after


def _slice(text: str, quote: Mapping[str, Any]) -> tuple[int, int, str]:
    for key in ("start", "end"):
        value = quote.get(key)
        if isinstance(value, bool) or not isinstance(value, int):
            _fail("PROPOSAL_OFFSET_INVALID", f"quote.{key} must be an integer, got {value!r}")
    start, end = quote["start"], quote["end"]
    if start < 0 or end <= start or end > len(text):
        _fail("PROPOSAL_OFFSET_OUT_OF_RANGE", f"quote [{start}:{end}] is outside the text (len {len(text)})")
    literal = quote.get("literal")
    if not isinstance(literal, str) or not literal:
        _fail("PROPOSAL_LITERAL_INVALID", "quote.literal must be a non-empty string")
    actual = text[start:end]
    if literal != actual:
        _fail("PROPOSAL_LITERAL_MISMATCH", f"quote.literal {literal!r} is not the actual slice {actual!r}")
    return start, end, actual


# ---------------------------------------------------------------------------
# public entry point
# ---------------------------------------------------------------------------

def verify_width_cap_proposal(text: Any, proposal: Any) -> dict[str, Any]:
    """Verify one width-cap proposal against the real request text.

    Example (accepted): text ``"整个板子横向最多九厘米。"`` with a quote over
    ``"整个板子横向最多九厘米"`` and the assertion ``value=9, unit="cm"`` returns
    ``value_mm=90.0`` — re-derived from the text, never taken from the model.
    """
    if not isinstance(text, str):
        _fail("PROPOSAL_TEXT_INVALID", "the request text must be a string")
    if len(text) > MAX_TEXT_CHARS:
        _fail("PROPOSAL_TEXT_TOO_LONG", f"the request text exceeds {MAX_TEXT_CHARS} characters")
    if not isinstance(proposal, Mapping):
        _fail("PROPOSAL_SHAPE_INVALID", "the proposal must be an object")
    _check_closed(proposal, _TOP_KEYS, "proposal")
    if proposal.get("field_path") != "plate.width":
        _fail("PROPOSAL_FIELD_PATH_INVALID", "only field_path='plate.width' is supported")
    if proposal.get("kind") != "upper_bound":
        _fail("PROPOSAL_KIND_INVALID", "only kind='upper_bound' is supported")

    quote = proposal.get("quote")
    if not isinstance(quote, Mapping):
        _fail("PROPOSAL_SHAPE_INVALID", "quote must be an object")
    _check_closed(quote, _QUOTE_KEYS, "quote")
    start, end, literal = _slice(text, quote)

    # Nothing semantic may sit outside the quote in the same clause: a subject-changing word
    # ("传感器"), a negation ("不是") or an extra condition ("大于") would make the quote a
    # misleading fragment. Only whitespace / punctuation / emoji are tolerated.
    context = _clause_context(text, start, end)
    if any(not _is_nonsemantic(char) for char in context):
        _fail("PROPOSAL_CONTEXT_NOT_SINGLE_CONDITION",
              "the quote is not the whole clause; supply the complete single-condition reference")

    # One complete single condition: width word + bound word + one number + one unit, nothing else.
    match = _CLAUSE_RE.match(_strip_decorations(literal))
    if not match:
        _fail("PROPOSAL_NOT_SINGLE_WIDTH_CAP",
              "the quote is not exactly one width upper bound (width word + bound word + number + unit)")
    _width_word, _bound_word, number_token, unit_word = match.groups()
    value = _parse_number(number_token)
    unit = UNIT_WORDS[unit_word]
    # The contract layer's fixed quantum is 9 decimals (convert_length): rounding removes float
    # representation noise (3 in -> 76.19999999999999). A value below that quantum rounds to 0 and
    # is refused rather than silently truncated toward zero.
    value_mm = round(value * UNIT_FACTORS_MM[unit], 9)
    if not math.isfinite(value_mm) or value_mm <= 0:
        _fail("PROPOSAL_VALUE_NOT_POSITIVE", f"the converted dimension {value_mm!r} is not a positive finite number")

    # The model's value/unit are assertions: refuse a mismatch rather than trust either side.
    asserted = proposal.get("value")
    if isinstance(asserted, bool) or not isinstance(asserted, (int, float)):
        _fail("PROPOSAL_ASSERTION_INVALID", "proposal.value must be a number")
    try:
        asserted_float = float(asserted)
    except (OverflowError, ValueError):
        # A pathologically large int (e.g. 10**400) must not leak a Python exception.
        _fail("PROPOSAL_ASSERTION_INVALID", "proposal.value is not representable as a finite number")
    if not math.isfinite(asserted_float):
        _fail("PROPOSAL_ASSERTION_INVALID", "proposal.value must be finite")
    if asserted_float != value:
        _fail("PROPOSAL_VALUE_MISMATCH", f"proposal.value {asserted!r} does not equal the re-derived {value!r}")
    if proposal.get("unit") != unit:
        _fail("PROPOSAL_UNIT_MISMATCH", f"proposal.unit {proposal.get('unit')!r} does not equal the re-derived {unit!r}")

    return {
        "field_path": "plate.width",
        "kind": "upper_bound",
        "value_mm": value_mm,
        "unit_in": unit,
        "source": {"kind": "text", "ref": f"text[{start}:{end}] {literal!r}"},
    }
